function [p, filepath] = write_aircraft_data(W0_design, WeightStruct, P_point, Neng, eb_star, overrides, fname)
% WRITE_AIRCRAFT_DATA  Generate the cost-model data sheet from sizing outputs.
%
% Inputs
%   W0_design    [lb]     design MTOW from weightIterationEstimate_new
%   WeightStruct [lb]     struct of component weights (needs fuel + battery fields)
%   P_point      [hp]     design power from PS_constraintcurves
%   Neng         [-]      total engine count (electric + combustion)
%   eb_star      [J/kg]   battery specific energy used in sizing
%   overrides    struct   (optional) any field of the defaults below, e.g.
%                         struct('ticket_price',250,'C_batt_kWh',400)
%   fname        char     (optional) function/file name, default 'aircraft_data_01'
%
% Outputs
%   p            struct   the data sheet values (same as calling the generated file)
%   filepath     char     full path of the generated .m file

    if nargin < 6 || isempty(overrides), overrides = struct(); end
    if nargin < 7 || isempty(fname),     fname = 'aircraft_data_01'; end

    % ---------- Pull values out of WeightStruct (lbs) ----------
    % Edit the name lists if your struct uses different field names.
    W_f_lb = getWeightField(WeightStruct, {'W_fuel','Wfuel','fuel','W_f','Wf'});
    W_b_lb = getWeightField(WeightStruct, {'W_batt','Wbatt','battery','W_b','Wb','W_battery'});

    % ---------- Default constants (non-sizing assumptions) ----------
    % RFP / logistics
    d.n_pax = 8;  d.R = 400;  d.then_year = 2035;
    d.tb = 3;  d.PLF = 0.75;  d.R_p = 1.0;  d.K_route = 2.75;  d.ticket_price = 200;
    % Fuel / oil
    d.P_f = 2.24;  d.rho_f = 6.7;  d.oil_frac = 0.01;  d.P_oil = 46;  d.rho_oil = 3.7;
    % Battery / electric
    d.DoD = 0.85;  d.eta_chg = 0.92;  d.P_elec = 0.15;
    % Hybrid architecture
    d.f_motor_power = 1.0;  d.C_motor_per_hp = 150;  d.C_batt_kWh = 520;
    % Crew & maintenance
    d.AF = 1.0;  d.R_L = 150;  d.H_em = 4000;
    % Ownership
    d.n_life = 20;  d.K_dep = 0.10;  d.IR_a = 0.02;  d.f_financing = 0.07;

    % Apply overrides
    ov = fieldnames(overrides);
    for k = 1:numel(ov)
        if ~isfield(d, ov{k})
            warning('write_aircraft_data:unknownOverride', ...
                    'Override "%s" is not a known constant and was ignored.', ov{k});
            continue
        end
        d.(ov{k}) = overrides.(ov{k});
    end

    % ---------- Derived values ----------
    lb2kg = 0.45359237;
    hp2kW = 0.7456999;

    MTOW_lb    = W0_design;                               % [lb]
    SHP_to     = P_point;                                 % [hp]
    PW_kWkg    = (SHP_to*hp2kW) / (MTOW_lb*lb2kg);        % [kW/kg]
    E_batt     = (W_b_lb*lb2kg) * (eb_star/3600) / 1000;  % [kWh] pack energy
    P_motor_hp = d.f_motor_power * SHP_to;                % [hp]

    % ---------- Write the file ----------
    fid = fopen([fname '.m'], 'w');
    assert(fid > 0, 'Could not open %s.m for writing', fname);
    cleaner = onCleanup(@() fclose(fid));   % closes file even if a write errors
    L = @(varargin) fprintf(fid, varargin{:});

    L('function p = %s()\n', fname);
    L('%% AUTO-GENERATED by write_aircraft_data on %s. Do not edit by hand;\n', datestr(now));
    L('%% change the driver or the overrides and rerun.\n');
    L('%% Values are referenced elsewhere as p.[value]\n');
    L('%% VARIABLE    %% VALUE     %% UNITS\n');
    L('%% ---------- RFP given values -----------------\n');
    L('p.n_pax        = %g;   %% [-]      passengers, from RFP\n', d.n_pax);
    L('p.R            = %g;   %% [nmi]    design range, from RFP\n', d.R);
    L('p.then_year    = %g;   %% [yr]     entry into service\n', d.then_year);
    L('%% ----------- Logistics -------------\n');
    L('p.tb           = %g;   %% [hr]     block time\n', d.tb);
    L('p.PLF          = %g;   %% [-]      passenger load factor\n', d.PLF);
    L('p.R_p          = %g;   %% [-]      ratio of pax legs (Roskam IOC term)\n', d.R_p);
    L('p.K_route      = %g;   %% [-]      route factor (2.75 = regional)\n', d.K_route);
    L('p.ticket_price = %g;   %% [$]      average one-way fare on the target route\n', d.ticket_price);
    L('%% ---------- Aircraft Specific (from sizing driver) ----------\n');
    L('p.MTOW         = %.2f;   %% [lb]     weightIterationEstimate_new\n', MTOW_lb);
    L('p.PW           = %.5f;   %% [kW/kg]  power-weight ratio (P_point / MTOW)\n', PW_kWkg);
    L('p.SHP_to       = %.2f;   %% [hp]     PS_constraintcurves design power\n', SHP_to);
    L('p.n_engines    = %d;   %% [-]      number of engines (Neng)\n', Neng);
    L('%% ---------- Fuel / Oil Specific (per trip) ----------\n');
    L('p.W_f          = %.2f;   %% [lb]     fuel weight (weight iteration code)\n', W_f_lb);
    L('p.P_f          = %g;   %% [$/gal]  Jet-A price (then-year $)\n', d.P_f);
    L('p.rho_f        = %g;   %% [lb/gal] Jet-A density\n', d.rho_f);
    L('p.oil_frac     = %g;   %% [-]      oil consumed as a fraction of block fuel\n', d.oil_frac);
    L('p.P_oil        = %g;   %% [$/gal]  oil price based on current data\n', d.P_oil);
    L('p.rho_oil      = %g;   %% [lb/gal] density of aircraft lubricant oil\n', d.rho_oil);
    L('p.W_oil        = 0.0125 * p.W_f * p.tb / 100;   %% [lb] weight of oil\n');
    L('%% ---------- Battery / Electric (per trip) ----------\n');
    L('p.W_b          = %.2f;   %% [lb]     installed pack weight\n', W_b_lb);
    L('p.DoD          = %g;   %% [-]      usable depth of discharge per trip\n', d.DoD);
    L('p.eta_chg      = %g;   %% [-]      wall-to-pack charging efficiency\n', d.eta_chg);
    L('p.P_elec       = %g;   %% [$/kWh]  electricity price (then-year $)\n', d.P_elec);
    L('%% ---------- Hybrid Architecture ----------\n');
    L('p.f_motor_power  = %g;   %% [-]    electric motor power as a fraction of SHP_to\n', d.f_motor_power);
    L('p.P_motor_hp     = %.2f;   %% [hp]   electric motor power (f_motor_power * SHP_to)\n', P_motor_hp);
    L('p.C_motor_per_hp = %g;   %% [$/hp]\n', d.C_motor_per_hp);
    L('p.C_batt_kWh     = %g;   %% [$/kWh]\n', d.C_batt_kWh);
    L('p.E_batt         = %.2f;   %% [kWh]  pack energy (W_b * %g Wh/kg)\n', E_batt, eb_star/3600);
    L('%% ---------- Crew & Maintenance ----------\n');
    L('p.AF           = %g;   %% [-]      crew airline factor (1.0 = high estimate)\n', d.AF);
    L('p.R_L          = %g;   %% [$/hr]   maintenance labour rate\n', d.R_L);
    L('p.H_em         = %g;   %% [hr]     hours between engine overhaul/swap\n', d.H_em);
    L('%% ---------- Ownership ----------\n');
    L('p.n_life       = %g;   %% [yr]     depreciation period\n', d.n_life);
    L('p.K_dep        = %g;   %% [-]      residual value fraction\n', d.K_dep);
    L('p.IR_a         = %g;   %% [1/yr]   hull insurance rate\n', d.IR_a);
    L('p.f_financing  = %g;   %% [-]      financing as a fraction of DOC\n', d.f_financing);
    L('end\n');
    clear cleaner;          % close the file now so MATLAB can load it
    rehash;

    filepath = fullfile(pwd, [fname '.m']);
    p = feval(fname);

    fprintf('Wrote %s  (MTOW = %.0f lb, SHP = %.0f hp, W_f = %.1f lb, W_b = %.1f lb, E_batt = %.0f kWh)\n', ...
            filepath, MTOW_lb, SHP_to, W_f_lb, W_b_lb, E_batt);
end

function val = getWeightField(S, names)
    for k = 1:numel(names)
        if isfield(S, names{k})
            val = S.(names{k});
            return
        end
    end
    error(['None of these fields found in WeightStruct: %s\n' ...
           'Available fields: %s\nEdit the name list in write_aircraft_data.'], ...
           strjoin(names, ', '), strjoin(fieldnames(S)', ', '));
end